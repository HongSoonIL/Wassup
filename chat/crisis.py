"""위기 신호 감지와 연기를 멈춘 안내 (설계서 3.3절, 3.10절).

위기 신호가 보이면 일과와 지연 규칙을 무시하고 바로 답한다. 답은 LLM이 만들지 않고
아래 고정 문구를 쓴다. 캐릭터 말투가 아니라 연기를 멈춘 안내이고, 109를 알려 준다.
"""

import re


# 놓치는 것보다 한 번 더 안내하는 쪽이 안전하므로 넓게 잡는다.
# "배고파 죽겠다"처럼 흔한 과장 표현(죽겠다)과 풋살의 "자살골"은 뺀다.
CRISIS_PATTERN = re.compile(
    r'자살(?!골)|자해|극단적\s*선택|스스로\s*목숨|목숨\s*을?\s*끊'
    r'|죽고\s*싶|죽어\s*버리고\s*싶|죽어버릴|죽을\s*래|죽을까\s*봐|그냥\s*죽을까'
    r'|살고\s*싶지\s*않|살기\s*싫|사는\s*게\s*의미\s*없|사라지고\s*싶|없어지고\s*싶'
    r'|뛰어\s*내리고\s*싶|뛰어\s*내릴|손목\s*을?\s*(긋|그었|그을)|유서'
)

CRISIS_BUBBLES = (
    '잠깐, 지금은 캐릭터 연기를 멈추고 말할게요. 저는 AI 친구라서 지금 곁에 직접 있어 줄 수는 없어요.',
    '혼자 견디지 않아도 돼요. 자살예방상담전화 109에 전화하면 24시간 언제든 상담사와 이야기할 수 있어요.',
    '지금 바로 위험하다고 느껴지면 112나 119에 연락해 주세요.',
)


def is_crisis(text):
    return bool(text) and CRISIS_PATTERN.search(text) is not None
